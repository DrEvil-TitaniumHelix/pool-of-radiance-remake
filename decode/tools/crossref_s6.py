"""CROSSREF section 6: data <-> code. Usage: python crossref_s6.py

(a) decode/data/INDEX.md "loaded by" column: every cited loader resolved to a function; confirmed when its listing
    references the group's file-name string (strings.tsv) or it calls LoadDaxRecord / LoadPicture.
(b) decode/data/SAVES.md field tables (TChar §3, item §4, effect §5, ITEMS §6): every row's cited reader routines are
    resolved and their .lst bodies searched for an access at the field offset: far records `[DI + off]` / `ES:[DI]`
    (off 0), ITEMS table `[DI + 5582h+j]` / `[0x5582+j...]`.
"""
import collections, csv, glob, os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import crossref as X

LINE = re.compile(r"^  ([0-9a-f]{4}):([0-9a-f]{4})  ([0-9a-f]+)\s+(\S+)\s*(.*)$")


def bodies():
    out = collections.defaultdict(list)
    for f in glob.glob(os.path.join(X.D, "listings/*.lst")):
        cur = None
        for ln in open(f, encoding="latin-1"):
            if ln.startswith(";==== "):
                cur = ln.split("@")[1].split()[0].upper(); continue
            if cur and LINE.match(ln): out[cur].append(ln.rstrip())
    return out


def resolver():
    merged, _ = X.names_merged()
    inv = collections.defaultdict(set)
    for k, (v, f) in merged.items():
        if not k.startswith("0C7C"): inv[v].add(k)
    for f in X.FUNCS: inv[f["name"]].add(f["key"])
    s2o = {}
    for f in X.FUNCS:
        m = re.match(r"ov(\d\d)", f["unit"])
        if m: s2o[m.group(1)] = f["key"][:4]
    funcs = {f["key"] for f in X.FUNCS}

    def res(text):
        keys = set()
        for m in re.finditer(r"\bov(\d\d)_([0-9A-Fa-f]{4})\b", text):
            s = s2o.get(m.group(1))
            if s: keys.add(("%s:%s" % (s, m.group(2))).upper())
        for m in re.finditer(r"\bFUN_([0-9A-Fa-f]{4})_([0-9A-Fa-f]{4})\b", text):
            keys.add(("%s:%s" % (m.group(1), m.group(2))).upper())
        for m in re.finditer(r"\b([0-9A-Fa-f]{4}):([0-9A-Fa-f]{4})\b", text):
            keys.add(("%s:%s" % (m.group(1), m.group(2))).upper())
        for w in set(re.findall(r"\b[A-Za-z_][A-Za-z0-9_]{3,}\b", text)):
            if w in inv and not X.PH.match(w): keys |= inv[w]
        return {k for k in keys if k in funcs}, merged
    return res


def main():
    res = resolver()
    B = bodies()
    merged, _ = X.names_merged()
    strs = collections.defaultdict(set)
    for r in csv.DictReader(open(os.path.join(X.D, "strings.tsv"), encoding="utf-8"), delimiter="\t"):
        for fn in r["referenced_by"].split(","):
            if fn: strs[fn.split("/")[-1]].add(r["text"].upper())
    fname = {f["key"]: f["name"] for f in X.FUNCS}
    callees = {f["key"]: f["callees"] for f in X.FUNCS}
    L = ["## 6. Data <-> code", "", "Generated by `decode/tools/crossref_s6.py` (byte-level checks against `decode/listings`).", "",
         "### 6a. DATA INDEX `loaded by` column — every loader resolved and checked", "",
         "| file(s) | loader (current name @ addr) | check |", "|---|---|---|"]
    ok_rows = 0; n_rows = 0
    for ln in open(os.path.join(X.D, "data/INDEX.md"), encoding="utf-8"):
        c = [x.strip() for x in ln.split("|")]
        if len(c) < 6 or not c[1] or c[1].startswith(("file", "---")) or "loaded by" in ln: continue
        if not re.search(r"\.DAX|ITEMS|SAV|POOL|START", c[1], re.I): continue
        keys, _ = res(c[5])
        group = re.sub(r"[^A-Z0-9]", " ", c[2].upper()).split()
        words = set(group) | set(re.findall(r"[A-Z][A-Z0-9]{2,}", c[1].upper().replace(".DAX", "")))
        out = []
        for k in sorted(keys):
            nm = merged.get(k, (fname.get(k, k),))[0]
            s = strs.get(fname.get(k, ""), set())
            hit = [w for w in words if any(w in t for t in s)]
            calls = callees.get(k, "")
            ld = [x for x in ("LoadDaxRecord", "LoadPicture", "LoadMonster", "ReadCharacter", "BlockRead") if x in calls]
            out.append("%s @ %s: %s" % (nm, k, ("string " + "/".join(sorted(hit)[:2])) if hit else (("calls " + ",".join(ld)) if ld else "not confirmed")))
        n_rows += 1
        good = out and all("not confirmed" not in o for o in out)
        ok_rows += bool(good)
        L.append("| %s | %s | %s |" % (c[1][:40], "<br>".join(out) or "(none cited)", "OK" if good else ("partial" if out else "—")))
    L += ["", "Rows: %d, all cited loaders confirmed: %d." % (n_rows, ok_rows), ""]
    # (b) SAVES.md field tables
    sec = None
    rows = []
    for ln in open(os.path.join(X.D, "data/SAVES.md"), encoding="utf-8"):
        m = re.match(r"^## (\d)\.", ln)
        if m: sec = m.group(1); continue
        c = [x.strip() for x in ln.split("|")]
        if sec in ("3", "4", "5", "6") and len(c) > 4 and re.fullmatch(r"\+?[0-9A-Fa-f]{1,3}h?(\.\.[0-9A-Fa-f]+h?)?", c[1] or "x"):
            off = int(c[1]) if sec == "6" else int(re.match(r"\+?([0-9A-Fa-f]+)", c[1]).group(1), 16)  # §6 column j is decimal
            rows.append((sec, off, c[3] if len(c) > 3 else "", " ".join(c[2:])))
    st = collections.Counter(); bad = []
    secreaders = collections.defaultdict(set)   # every routine cited anywhere in the section = known readers of that record
    for sec, off, name, text in rows:
        secreaders[sec] |= res(text)[0]
    for sec, off, name, text in rows:
        keys, _ = res(text)
        if sec == "6":
            pats = [r"\b0x%x\b" % (0x5582 + off)]   # any operand with the field's DS address ([DI+a], [a], LEA/MOV r,a)
        else:
            pats = [r"ES:\[DI \+ 0x%x\]" % off] if off else [r"ES:\[DI\]"]
        def hit(k, strict=False):
            body = B.get(k, [])
            if any(re.search(p, l) for l in body for p in pats): return True
            if strict: return False
            # ITEMS via a computed base: "ADD DI,0x5582" followed within 12 instructions by [DI + j]
            if sec != "6": return False
            for n, l in enumerate(body):
                if "ADD DI,0x5582" in l and any(re.search(r"\[DI \+ 0x%x\]" % off, m) for m in body[n + 1:n + 13]):
                    return True
                # whole entry copied to a local first: LEA DI,[BP + -0xL] ... CopyBytes(16) ... [BP + -0x(L-j)]
                if "ADD DI,0x5582" in l:
                    for m in body[n + 1:n + 5]:
                        mm = re.search(r"LEA DI,\[BP \+ -0x([0-9a-f]+)\]", m)
                        if mm and any("CopyBytes" in x for x in body[n + 1:n + 9]):
                            loc = int(mm.group(1), 16) - off
                            if loc > 0 and any(("[BP + -0x%x]" % loc) in x for x in body[n + 8:n + 80]):
                                return True
            return False
        found = [k for k in keys if hit(k)]
        other = [] if found else sorted(k for k in secreaders[sec] - keys if hit(k))
        if sec == "6" and not found and not other:   # ITEMS fields have fixed DS addresses: a global search is unambiguous
            other = sorted(k for k in B if hit(k, strict=True))
        r = "confirmed" if found else ("confirmed in another reader of this record" if other else ("cited, access not found" if keys else "no reader cited"))
        if other: keys = set(other[:3])
        st[(sec, r)] += 1
        if not found and not other: bad.append((sec, off, name, r, ", ".join(sorted(merged.get(k, (k,))[0] for k in keys))[:80]))
    L += ["### 6b. SAVES.md field readers (section, result: count)", "",
          "| section | record | confirmed in a cited reader | confirmed in another reader of the record | cited, access not found | no reader found |", "|---|---|---|---|---|---|"]
    for s, nm in (("3", "TChar 285 B"), ("4", "item 63 B"), ("5", "effect 9 B"), ("6", "ITEMS type table")):
        L.append("| §%s | %s | %d | %d | %d | %d |" % (s, nm, st[(s, "confirmed")], st[(s, "confirmed in another reader of this record")], st[(s, "cited, access not found")], st[(s, "no reader cited")]))
    L += ["", "Second pass: when the cited routines do not contain the access, every routine cited anywhere in the same section (known readers of that record type) is searched; a hit counts as confirmed in another reader.", "", "Rows not confirmed (field offset, name, result, cited routines) — `data fix request #xref-5` (por-data/por-saves: cite a reader or mark the field unused/unknown). Checker limits (not data errors): fields read through an index added to the base (e.g. `str + i` read as `[DI+10h]` after `ADD DI,i`: int/dex), or after a block copy to a local; the ITEMS table handles both forms.", "",
          "| § | off | field | result | cited |", "|---|---|---|---|---|"]
    for sec, off, name, r, k in bad:
        L.append("| %s | %Xh | %s | %s | %s |" % (sec, off, name.replace("|", "/"), r, k))
    X.write("s6_data", "\n".join(L) + "\n")
    print(n_rows, ok_rows, dict(st))


if __name__ == "__main__":
    main()
