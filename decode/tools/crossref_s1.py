"""CROSSREF section 1 (unit -> area -> file). Usage: python crossref_s1.py"""
import collections, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import crossref as X

NOTES = {
    'ov07': 'also decoded in COMBAT (combat_parts/ov07.pas.md = second decode); COMBAT.pas.md section is a pointer. 33/33 names agree, bodies equivalent',
    'ov08': 'combat round loop (CombatMain, NextToAct) lives in MAGIC.pas.md per the area map (recorded, left there)',
    'ov22': 'spell handlers documented as table rows in MAGIC.pas.md; 8E00:1C31, 1DAA, 1DBE, 1DC1 = Ghidra fragments inside the preceding spell routine (start mid-loop / are JMP stubs; codex draft also flags them), not routines',
    'ov16': '7000:1551 (and 1156, 14A7) were Ghidra splits of 7000:056C, folded back by the PorBuild orphan cleanup; PARTY.pas.md documents this',
    'ov19': 'proposed move to PARTY (party/inventory UI); stays in COMBAT.pas.md',
    'res_08AE': 'ENGINE also documents 5 internal entries without Ghidra functions (13EA, 1477, 14EC, 157A, 160B)',
    'res_03DA': 'empty-init unit (`55 89 E5 5D CB` only); assigned ENGINE', 'res_03ED': 'empty-init unit; assigned ENGINE',
    'res_0A31': 'empty-init unit; assigned ENGINE'}
FILE = {'ENGINE': 'ENGINE.pas.md', 'ECL': 'ECL.pas.md', 'VIEW': 'VIEW.pas.md', 'COMBAT': 'COMBAT.pas.md', 'MAGIC': 'MAGIC.pas.md',
        'PARTY': 'PARTY.pas.md', 'PARTY(parts)': 'party_parts/ (PARTY.pas.md pending)'}


def main():
    rows, hd = X.sec_units()
    have = collections.defaultdict(set)
    for a, l in hd.items():
        for addr, n, c, pp in l: have[addr].add(a)
    L = ['## 1. Unit -> area -> pseudo file (canonical)', '',
         'Every one of the 52 code units has exactly one canonical home. Coverage = routine headers in the canonical file / functions in `decode/listings/functions.tsv`; combined headers (`### A / B`) and init lines count. Generated by `decode/tools/crossref_s1.py`.', '',
         '| unit | canonical area | file | coverage | notes |', '|---|---|---|---|---|']
    todo = 0
    for u, areas, txt, n, _ in rows:
        if u in ('res_03DA', 'res_03ED', 'res_0A31'):
            L.append('| %s | ENGINE | — | 1 init | %s |' % (u, NOTES[u])); continue
        if areas == 'RUNTIME':
            L.append('| %s | RUNTIME | decode/rt/%s | %d | TP runtime, verified ledger |' % (u, txt, n)); continue
        if areas == '—':
            L.append('| stubs | — | LAYOUT.md | %d thunks | overlay stub entries |' % n); continue
        fa = [f['key'] for f in X.FUNCS if f['unit'] == u]
        if areas == 'NONE':
            L.append('| %s | PARTY (pending) | — | 0/%d | final not yet written |' % (u, len(fa))); todo += 1; continue
        canon = 'ECL' if u == 'ov07' else areas.split(',')[0]
        c = sum(1 for k in fa if canon in have.get(k, ()))
        note = NOTES.get(u, '' if c == len(fa) else 'INCOMPLETE')
        if c < len(fa) and u not in NOTES: todo += 1
        L.append('| %s | %s | %s | %d/%d | %s |' % (u, canon.replace('(parts)', ' (parts)'), FILE.get(canon, canon), c, len(fa), note))
    L += ['', 'Units with undocumented routines (excluding explained fragments): %d.' % todo]
    X.write('s1_units', '\n'.join(L) + '\n')
    print('\n'.join(L))


if __name__ == '__main__':
    main()
