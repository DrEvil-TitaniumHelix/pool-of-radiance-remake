"""CROSSREF section 5: unknown roll-up. Usage: python crossref_s5.py"""
import collections, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import crossref as X
import crossref_s3 as S3

OWN = {'ENGINE': 'por-mod-engine', 'ECL': 'por-ecl', 'VIEW': 'por-mod-view', 'COMBAT': 'por-mod-combat', 'MAGIC': 'por-mod-magic',
       'PARTY': 'por-mod-party', 'PARTY(parts)': 'por-mod-party', 'DATA': 'por-data', 'RUNTIME': 'por-rt'}


def main():
    ua = S3.unit_areas()
    merged, _ = X.names_merged()
    rows = X.sec_unknowns()
    L = ['## 5. Unknown roll-up', '',
         'Every remaining placeholder across the pseudo, data and ECL files (distinct tokens per file). `FUN_`/`ovNN_XXXX` = unnamed routine; `g_XXXX` = unnamed global; `unk_`/`UNKNOWN` = explicit unknowns; L = routine headers with confidence L. Owner = the lane that owns the file. Generated by `decode/tools/crossref_s5.py`.', '',
         '### 5a. Per file', '', '| area | file | FUN_ | ovNN_ | g_ | unk_/UNKNOWN | L headers | owner |', '|---|---|---|---|---|---|---|---|']
    tot = collections.Counter()
    for a, f, fun, ovn, g, unk, lc in rows:
        L.append('| %s | %s | %d | %d | %d | %d | %d | %s |' % (a, f, fun, ovn, g, unk, lc, OWN.get(a, '?')))
        tot.update(dict(fun=fun, ovn=ovn, g=g, unk=unk, l=lc))
    L.append('| **total** | | %d | %d | %d | %d | %d | |' % (tot['fun'], tot['ovn'], tot['g'], tot['unk'], tot['l']))
    # routines without a real name
    un = collections.defaultdict(list)
    for f in X.FUNCS:
        if f['unit'] == 'stubs': continue
        v = merged.get(f['key'])
        if not v or X.PH.match(v[0]):
            un[f['unit']].append(f['key'])
    L += ['', '### 5b. Routines still without a real name (merged names map vs functions.tsv)', '',
          '| unit | area | owner | unnamed / total | addresses |', '|---|---|---|---|---|']
    cnt = collections.Counter(f['unit'] for f in X.FUNCS)
    tu = 0
    for u in X.UNITS:
        if u in un:
            a = ua.get(u, '?'); tu += len(un[u])
            L.append('| %s | %s | %s | %d/%d | %s |' % (u, a, OWN.get(a, '?'), len(un[u]), cnt[u], ' '.join(k[5:] for k in un[u][:30]) + (' …' if len(un[u]) > 30 else '')))
    L += ['', 'Routines without a real name: %d of %d (excluding 406 stub thunks). Init routines (`ovNN_init`, empty) are included and need no name.' % (tu, sum(v for k, v in cnt.items() if k != 'stubs')), '',
          'Shared globals still `g_XXXX`: see §3 (rows whose name starts with g_); owner = the area that writes them (§3 writers column).']
    X.write('s5_unknowns', '\n'.join(L) + '\n')
    print(dict(tot), tu)


if __name__ == '__main__':
    main()
