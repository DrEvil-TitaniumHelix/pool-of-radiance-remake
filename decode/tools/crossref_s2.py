"""CROSSREF section 2: routine-name consistency.

Usage: python crossref_s2.py [--apply]
--apply: replace stale placeholders (FUN_SSSS_OOOO / ovNN_XXXX where a real published name exists) in the files of
areas whose owner is DONE (ENGINE, ECL, VIEW, COMBAT incl. combat_parts). MAGIC/PARTY (DONE since) are included too.
"""
import collections, glob, os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import crossref as X

DONE_FILES = ["decode/pseudo/ENGINE.pas.md", "decode/pseudo/ECL.pas.md", "decode/pseudo/VIEW.pas.md",
              "decode/pseudo/COMBAT.pas.md", "decode/pseudo/ENGINE_SCREENS.md", "decode/pseudo/ECL_SCREENS.md",
              "decode/pseudo/VIEW_SCREENS.md", "decode/pseudo/COMBAT_SCREENS.md"] + \
             sorted(glob.glob(os.path.join(X.R, "decode/pseudo/combat_parts/*.md"))) + \
             ["decode/pseudo/MAGIC.pas.md", "decode/pseudo/MAGIC_SCREENS.md", "decode/pseudo/PARTY.pas.md", "decode/pseudo/PARTY_SCREENS.md"] + \
             sorted(glob.glob(os.path.join(X.R, "decode/pseudo/party_parts/*.md")))   # MAGIC/PARTY owners DONE: applied directly
OPEN_FILES = {}


def seg2ov():
    m = {}
    for f in X.FUNCS:
        mm = re.match(r"ov(\d\d)", f["unit"])
        if mm: m[mm.group(1)] = f["key"][:4]
    return m


def stale_in(path, merged, s2o):
    t = open(os.path.join(X.R, path) if not os.path.isabs(path) else path, encoding="utf-8", errors="replace").read()
    hits = collections.Counter()

    def rep(m):
        if m.group(1):
            k = ("%s:%s" % (m.group(1), m.group(2))).upper()
        else:
            s = s2o.get(m.group(3))
            if not s: return m.group(0)
            k = ("%s:%s" % (s, m.group(4))).upper()
        pub = merged.get(k)
        if pub and not X.PH.match(pub[0]):
            hits[(m.group(0), pub[0])] += 1
            return pub[0]
        return m.group(0)
    new = re.sub(r"\bFUN_([0-9a-fA-F]{4})_([0-9a-fA-F]{4})\b|\bov(\d\d)_([0-9A-Fa-f]{4})\b", rep, t)
    return t, new, hits


def main():
    apply = "--apply" in sys.argv
    merged, _ = X.names_merged()
    s2o = seg2ov()
    done_tot = collections.Counter()
    for p in DONE_FILES:
        rel = os.path.relpath(p, X.R) if os.path.isabs(p) else p
        t, new, hits = stale_in(p, merged, s2o)
        n = sum(hits.values())
        done_tot[rel] = n
        if apply and n:
            open(os.path.join(X.R, rel), "w", encoding="utf-8").write(new)
    for area, files in OPEN_FILES.items():
        lines = ["# Stale placeholders in %s files (generated by crossref_s2.py) — `%s fix request #xref-3`" % (area, area.lower()), "",
                 "Each placeholder below has a published real name (decode/names/*.json); please write the name.", "",
                 "| file | placeholder | published name | count |", "|---|---|---|---|"]
        tot = 0
        for p in files:
            rel = os.path.relpath(p, X.R) if os.path.isabs(p) else p
            if not os.path.exists(os.path.join(X.R, rel)): continue
            _, _, hits = stale_in(p, merged, s2o)
            for (ph, nm), c in sorted(hits.items()):
                lines.append("| %s | %s | %s | %d |" % (rel, ph, nm, c)); tot += c
        lines.append("\nTotal: %d" % tot)
        X.write("stale_%s" % area, "\n".join(lines) + "\n")
        print(area, "stale", tot)
    for k, v in done_tot.items():
        if v: print(("applied " if apply else "would apply ") + str(v), k)


if __name__ == "__main__":
    main()
