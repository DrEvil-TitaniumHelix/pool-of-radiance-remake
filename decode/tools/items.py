#!/usr/bin/env python3
"""Item tools for Pool of Radiance. Spec: decode/data/SAVES.md §4/§6, decode/data/ITEMS.md.

  items.py md               -> writes decode/data/ITEMS.md (type table + name-word table + item examples)
  items.py dump FILE        -> lists the 63-byte item records of a .ITM / MONnITM / ITEMn record file

Needs decode/bin/START.unpacked.exe (name words at DS:10A7, DS = 0C7C) and the original ITEMS file.
"""
import glob
import os
import struct
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), '..', '..'))
POOL = os.path.normpath(os.path.join(ROOT, '..', 're-targets', 'goldbox', 'por', 'POOLRAD'))
EXE = os.path.join(ROOT, 'decode', 'bin', 'START.unpacked.exe')
DS = 0x0C7C * 16
WORDS_DS = 0x10A7          # 1-based: word w at DS:10A7 + w*21, string[20]
TYPES_FILE_OFS = 2         # ov11_002D: Seek(2) then BlockRead into DS:5582


def image():
    exe = open(EXE, 'rb').read()
    hdr = struct.unpack_from('<H', exe, 8)[0] * 16
    return exe[hdr:]


def words():
    d = image()
    out = {}
    for w in range(1, 256):
        a = DS + WORDS_DS + w * 21
        n = d[a]
        out[w] = d[a + 1:a + 1 + n].decode('latin-1') if n <= 20 else '?'
    return out


def types():
    b = open(os.path.join(POOL, 'ITEMS'), 'rb').read()
    return [b[TYPES_FILE_OFS + t * 16:TYPES_FILE_OFS + t * 16 + 16] for t in range(128)]


def item_name(r, W, identified=True):
    parts = []
    for k in (3, 2, 1):                      # FUN_00BA_0442 order: +31h, +30h, +2Fh
        w = r[0x2E + k]
        hidden = (r[0x35] >> (3 - k)) & 1
        if w and (identified or not hidden):
            parts.append(W.get(w, '?'))
    s = ' '.join(parts)
    if r[0x39]:
        s = '%d %s' % (r[0x39], s)
    return s


def parse(r):
    return {'type': r[0x2E], 'words': tuple(r[0x2F:0x32]), 'plus': struct.unpack('b', r[0x32:0x33])[0],
            'plus2': struct.unpack('b', r[0x33:0x34])[0], 'readied': r[0x34], 'hidden': r[0x35],
            'magic': r[0x36], 'weight': struct.unpack_from('<H', r, 0x37)[0], 'count': r[0x39],
            'value': struct.unpack_from('<H', r, 0x3A)[0], 'power': r[0x3C:0x3F].hex(' ')}


def all_items():
    files = sorted(glob.glob(os.path.join(POOL, 'SAVE', '*.ITM')))
    files += sorted(glob.glob(os.path.join(ROOT, 'decode', 'bin', 'dax', '*ITM', '*.bin')))
    files += sorted(glob.glob(os.path.join(ROOT, 'decode', 'bin', 'dax', 'ITEM*', '*.bin')))
    for f in files:
        b = open(f, 'rb').read()
        for k in range(len(b) // 63):
            yield f, b[k * 63:(k + 1) * 63]


SLOT = {0: 'weapon', 1: 'shield', 2: 'armour', 9: 'ring', 0x0A: 'ammo/misc', 0x0B: 'MU scroll', 0x0C: 'cleric scroll'}


def write_md():
    W = words()
    T = types()
    ex = {}
    for f, r in all_items():
        ex.setdefault(r[0x2E], set()).add(item_name(r, W))
    L = ['# ITEMS — item-type table, item-name words, item inventory (generated by decode/tools/items.py md)', '',
         'Record layouts and code evidence: [SAVES.md](SAVES.md) §4 (63-byte item) and §6 (ITEMS file). '
         'ITEMS (2050 B) is read by ov11_002D with Seek(2) + BlockRead(2048) into DS:5582: type t = file[2+16t .. 17+16t]. '
         'Columns j0..j15 as in SAVES.md §6 (slot, hands, dice/sides/bonus vs large, rof, ac_value, wflags, j8, '
         'dice/sides/bonus vs S/M, range, usable_by (class mask: 1 MU, 2 cleric, 4 thief, 8 fighter), wflags2, j15).', '',
         '"Seen as" = names of real item records (saves, MONnITM, ITEMn) with this type, built like FUN_00BA_0442 (identified).', '',
         '## Item-type table (128 types)', '',
         '| t | j0 slot | j1 hands | vs L | rof | ac | wfl | j8 | vs S/M | range | usable | wfl2 | raw | seen as |',
         '|---|---|---|---|---|---|---|---|---|---|---|---|---|---|']
    for t, e in enumerate(T):
        vsl = '%dd%d%+d' % (e[2], e[3], struct.unpack('b', e[4:5])[0]) if e[2] else '-'
        vsm = '%dd%d%+d' % (e[9], e[10], struct.unpack('b', e[11:12])[0]) if e[9] else '-'
        ac = ('AC %d' % (60 - (e[6] & 0x7F)) if e[6] & 0x7F > 9 else '+%d' % (e[6] & 0x7F)) if e[6] & 0x80 else '-'
        seen = '; '.join(sorted(ex.get(t, []))[:4])
        L.append('| %d | %s | %d | %s | %d | %s | %02x | %02x | %s | %d | %02x | %02x | `%s` | %s |' % (
            t, SLOT.get(e[0], '%d' % e[0]), e[1], vsl, e[5], ac, e[7], e[8], vsm, e[12], e[13], e[14], e.hex(' '), seen))
    L += ['', '## Item-name words (DS:10A7 + w·21, string[20], 1-based; read from the resident image)', '',
          '| w | word | w | word | w | word | w | word |', '|---|---|---|---|---|---|---|---|']
    ws = list(range(1, 256))
    for i in range(0, len(ws), 4):
        row = []
        for w in ws[i:i + 4]:
            row += ['%d (%02Xh)' % (w, w), W[w] or '·']
        while len(row) < 8:
            row += ['', '']
        L.append('| ' + ' | '.join(row) + ' |')
    L += ['', 'Base weapons and armour use the word with their own type number (types 1..47, 50..59); words 48 "Mail" '
          'and 49 "Armor" are suffixes (Banded Mail = words 39h + 30h, Leather Armor = 32h + 31h) and types 48/49 are empty. '
          'Magic items combine words, e.g. "Long Sword +1" = +31h 24h (Long Sword), +30h A2h (+1), +2Fh 00h. '
          'j0 values >= 0Ah other than the scroll/ring/ammo ones (4Ah, 4Bh, 4Dh, 4Eh …) are never < 9 or = 9, so these '
          'types cannot be readied into a body slot (Recalc).', '']
    with open(os.path.join(ROOT, 'decode', 'data', 'ITEMS.md'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(L))
    print('ITEMS.md written, %d types, %d typed examples' % (len(T), len(ex)))


def dump(path):
    W = words()
    b = open(path, 'rb').read()
    for k in range(len(b) // 63):
        r = b[k * 63:(k + 1) * 63]
        print('%2d %-36s %s' % (k, item_name(r, W), parse(r)))


def main(argv):
    if len(argv) >= 2 and argv[1] == 'md':
        write_md()
        return 0
    if len(argv) >= 3 and argv[1] == 'dump':
        dump(argv[2])
        return 0
    print(__doc__)
    return 1


if __name__ == '__main__':
    sys.exit(main(sys.argv))
